"""Run the comparative experiments on real Loghub datasets and write docs/experiments.md + docs/experiments_results.json.

Usage (from backend/):  python scripts/run_experiments.py [--datasets Linux OpenSSH ...] [--embeddings]
Every number in the output comes from this run; nothing is hardcoded. Requires internet for the first download.
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DATABASE_URL", f"sqlite:///{(ROOT / 'data' / 'experiments.db').as_posix()}")

from app.database.session import SessionLocal, init_db  # noqa: E402
from app.services import datasets as ds  # noqa: E402
from app.services.analysis import analyze  # noqa: E402
from app.services.jobs import parse_files  # noqa: E402

DOCS = ROOT.parent / "docs"
DEFAULT = ["Linux (Loghub 2k)", "Apache (Loghub 2k)", "OpenSSH (Loghub 2k)", "HDFS (Loghub 2k)", "BGL (Loghub 2k)", "HealthApp (Loghub 2k)"]


def fmt(v):
    return "-" if v is None else f"{v:.3f}" if isinstance(v, float) else str(v)


def scalability() -> list[dict]:
    """Synthetic scalability test (clearly labelled): replicate the bundled app log with varied numbers to reach larger sizes."""
    import re
    base = (ROOT / "sample_data" / "app_service.log").read_text().splitlines()
    out = []
    for mult in (1, 4, 16):
        lines = []
        for k in range(mult):
            lines += [re.sub(r"\d{2}:\d{2}:\d{2}\.\d+", lambda m: m.group(0), l) if k == 0 else l.replace("2026-03-14", f"2026-03-{14 + k:02d}") for l in base]
        rows = parse_files([{"name": "scale.log", "data": "\n".join(lines).encode()}])[0]
        t0 = time.perf_counter()
        r = analyze(rows, {"run_evaluation": False})
        dt = time.perf_counter() - t0
        out.append({"logs": len(rows), "seconds": round(dt, 2), "logs_per_second": round(len(rows) / dt), "stage_seconds": r["evaluation"]["timings_s"]})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets", nargs="*", default=DEFAULT)
    ap.add_argument("--skip-scalability", action="store_true")
    a = ap.parse_args()
    init_db()
    results = {"generated": time.strftime("%Y-%m-%d %H:%M:%S"), "datasets": {}}
    for name in a.datasets:
        print("==", name, flush=True)
        with SessionLocal() as db:
            f = ds.load_dataset(db, name)
        labels = json.loads(Path(f.labels_path).read_text()) if f.labels_path else None
        rows, meta = parse_files([{"name": f.filename, "data": Path(f.stored_path).read_bytes(), "labels": labels}])
        res = analyze(rows, {"run_evaluation": True, "evaluation_max_unique": 4000})
        ev = res["evaluation"]
        results["datasets"][name] = {"logs": len(rows), "format": meta["files"][0]["format"], "templates_drain": res["stats"]["n_templates"], "evaluation": ev,
                                     "n_true_templates": len(set(labels)) if labels else None}
    if not a.skip_scalability:
        results["scalability_synthetic"] = scalability()
    DOCS.mkdir(exist_ok=True)
    (DOCS / "experiments_results.json").write_text(json.dumps(results, indent=2, default=str))
    md = ["# Experiment results", "", f"_Generated by `backend/scripts/run_experiments.py` on {results['generated']}. Every value below was measured in that run; "
          "re-run the script to reproduce (timings vary by machine)._", ""]
    for name, d in results["datasets"].items():
        ev = d["evaluation"]
        md += [f"## {name}", f"{d['logs']:,} log lines, parsed as `{d['format']}`; Drain3 found **{d['templates_drain']}** templates"
               + (f" (ground truth: {d['n_true_templates']} event templates)." if d["n_true_templates"] else "."), ""]
        if "template_methods" in ev:
            md += ["**Template extraction**", "", "| method | templates | runtime s | logs/s | grouping accuracy |", "|---|---|---|---|---|"]
            md += [f"| {k} | {v['n_templates']} | {v['runtime_s']} | {v['logs_per_s']} | {fmt(v.get('grouping_accuracy'))} |" for k, v in ev["template_methods"].items()]
            md.append("")
        comp = ev.get("comparison", {})
        if comp.get("warning"):
            md += [f"> WARNING: {comp['warning']}", ""]
        if comp.get("note"):
            md += [f"_{comp['note']}_", ""]
        sup = comp.get("supervised")
        cols = ["ari", "nmi", "v_measure"] if sup else []
        header = ["features", "backend", "algorithm", "clusters", "noise"] + cols + ["silhouette", "davies_bouldin", "calinski_harabasz", "cluster s", "feature s", "peak MB"]
        md += ["**Clustering grid** (features x algorithm; K-Means uses k = min(#Drain templates, 50))", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
        for g in comp.get("grid", []):
            if "error" in g:
                md.append(f"| {g['features']} | {g['feature_backend']} | {g['algorithm']} | error: {g['error']} |")
                continue
            m = g["metrics"]
            md.append(f"| {g['features']} | {g['feature_backend']} | {g['algorithm']} | {m['n_clusters']} | {m['noise_ratio']} | " + " | ".join(fmt(m.get(c)) for c in cols + ["silhouette", "davies_bouldin", "calinski_harabasz"])
                      + f" | {g['cluster_seconds']} | {g['feature_seconds']} | {g['peak_memory_mb']} |")
        md.append("")
        if "anomaly" in ev:
            md += ["**Anomaly detection** (labels = BGL alert flag)", "", "| detector | precision | recall | F1 | ROC-AUC | PR-AUC |", "|---|---|---|---|---|---|"]
            md += [f"| {k} | {fmt(v.get('precision'))} | {fmt(v.get('recall'))} | {fmt(v.get('f1'))} | {fmt(v.get('roc_auc'))} | {fmt(v.get('pr_auc'))} |" for k, v in ev["anomaly"].items()]
            md.append("")
        md += [f"Total pipeline time {ev['total_seconds']} s ({ev['logs_per_second']} logs/s incl. evaluation grid).", ""]
    if "scalability_synthetic" in results:
        md += ["## Scalability (synthetic data - replicated bundled log, evaluation grid disabled)", "", "| logs | seconds | logs/s |", "|---|---|---|"]
        md += [f"| {s['logs']:,} | {s['seconds']} | {s['logs_per_second']:,} |" for s in results["scalability_synthetic"]]
    (DOCS / "experiments.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote docs/experiments.md")


if __name__ == "__main__":
    main()
